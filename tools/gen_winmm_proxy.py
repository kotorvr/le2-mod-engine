"""Generate the winmm.dll pass-through for the loader from System32\\winmm.dll's export table.

Writes loader/src/winmm.def, loader/src/winmm_stubs.S and loader/src/winmm_names.inc. Every export becomes a
one-instruction stub that jumps through a pointer filled in from the real System32 winmm.dll at load, so any module
in the game process that binds to our winmm.dll still reaches the real function. Ordinals are kept.

    python tools/gen_winmm_proxy.py
"""
import pathlib

import pefile

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "loader" / "src"


def main():
    pe = pefile.PE(r"C:\Windows\System32\winmm.dll", fast_load=True)
    pe.parse_data_directories([0])
    exports = sorted(pe.DIRECTORY_ENTRY_EXPORT.symbols, key=lambda e: e.ordinal)

    defl = ["LIBRARY winmm.dll", "EXPORTS"]
    asm = [
        "// Generated by tools/gen_winmm_proxy.py. Do not edit.",
        "    .text",
    ]
    names = ["// Generated by tools/gen_winmm_proxy.py. Do not edit.", "// { name or nullptr, ordinal }"]
    for i, e in enumerate(exports):
        stub = f"le2_winmm_stub_{i}"
        asm += [f"    .globl {stub}", f"{stub}:", f"    jmp *le2_winmm_real+{i * 8}(%rip)"]
        if e.name:
            name = e.name.decode()
            defl.append(f"    {name}={stub} @{e.ordinal}")
            names.append(f'    {{ "{name}", {e.ordinal} }},')
        else:
            defl.append(f"    __winmm_ord{e.ordinal}={stub} @{e.ordinal} NONAME")
            names.append(f"    {{ nullptr, {e.ordinal} }},")
    # DirectInput-free proxy: nothing else exported.
    (OUT / "winmm.def").write_text("\n".join(defl) + "\n", encoding="ascii")
    (OUT / "winmm_stubs.S").write_text("\n".join(asm) + "\n", encoding="ascii")
    (OUT / "winmm_names.inc").write_text("\n".join(names) + "\n", encoding="ascii")
    print(f"{len(exports)} winmm exports")


if __name__ == "__main__":
    main()
