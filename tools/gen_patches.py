"""Turn patches/*.json into loader/src/patches_gen.inc (compiled into dinput8.dll).

Each JSON follows docs/PATCH_SPEC.md. Run after editing any patch file:

    python tools/gen_patches.py
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "patches"
OUT = ROOT / "loader" / "src" / "patches_gen.inc"


def hexbytes(text):
    data = bytes.fromhex(text.replace(" ", ""))
    return ", ".join(f"0x{b:02x}" for b in data), len(data)


def c_str(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    features = []
    runtime = []
    for path in sorted(SRC.glob("*.json")):
        spec = json.loads(path.read_text(encoding="utf-8"))
        rows = spec.get("patches", []) + spec.get("values", [])
        if spec.get("runtime"):
            runtime.append((path.stem, spec))  # implemented in loader code, listed for the app only
            continue
        if not rows and not spec.get("call_hooks"):
            print(f"skip {path.name}: no patches", file=sys.stderr)
            continue
        features.append((path.stem, spec, rows))

    lines = ["// Generated by tools/gen_patches.py from patches/*.json. Do not edit.", ""]
    for fid, spec, rows in features:
        hooks = spec.get("call_hooks", [])
        for i, h in enumerate(hooks):
            writes = ", ".join(f"{{ {w['offset']}, {float(w['float'])}f }}" for w in h["writes"])
            lines.append(f"static const FloatWrite k_{fid}_h{i}_w[] = {{ {writes} }};")
        lines.append(f"static const CallHook k_{fid}_hooks[] = {{")
        for i, h in enumerate(hooks):
            lines.append(f"    {{ {h['site']}, {h['callee']}, {int(h['arg'])}, k_{fid}_h{i}_w, {len(h['writes'])} }},")
        if not hooks:
            lines.append("    { 0, 0, 0, nullptr, 0 },")
        lines.append("};")
        for i, row in enumerate(rows):
            exp, n1 = hexbytes(row["expect"])
            rep, n2 = hexbytes(row["replace"])
            if n1 != n2:
                raise SystemExit(f"{fid} patch {i}: expect and replace lengths differ")
            lines.append(f"static const uint8_t k_{fid}_{i}_e[] = {{ {exp} }};")
            lines.append(f"static const uint8_t k_{fid}_{i}_r[] = {{ {rep} }};")
        lines.append(f"static const PatchBytes k_{fid}[] = {{")
        for i, row in enumerate(rows):
            module = row["module"]
            mod = "nullptr" if module == "exe" else c_str(module)
            n = len(bytes.fromhex(row["expect"].replace(" ", "")))
            lines.append(f"    {{ {mod}, {row['rva']}, k_{fid}_{i}_e, k_{fid}_{i}_r, {n} }},")
        if not rows:
            lines.append("    { nullptr, 0, nullptr, nullptr, 0 },")
        lines.append("};")
        lines.append("")
    lines.append("static const FeatureDef k_features[] = {")
    for fid, spec, rows in features:
        live = "true" if spec.get("live") else "false"
        nh = len(spec.get("call_hooks", []))
        lines.append(f"    {{ {c_str(fid)}, {live}, k_{fid}, {len(rows)}, k_{fid}_hooks, {nh} }},")
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    # The GUI greys out switches the loader doesn't have patches for.
    manifest = {fid: {"live": bool(spec.get("live")), "patches": len(rows),
                      "call_hooks": len(spec.get("call_hooks", [])),
                      "experimental": bool(spec.get("experimental"))} for fid, spec, rows in features}
    for fid, spec in runtime:
        manifest[fid] = {"live": False, "runtime": True, "experimental": bool(spec.get("experimental"))}
    (ROOT / "engine" / "features.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} and engine/features.json: {len(features)} features")


if __name__ == "__main__":
    main()
